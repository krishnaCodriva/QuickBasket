// Generate a nested object map of keys so STRINGS.common.appName === 'common.appName'
type DeepKeyOf<T> = {
  [K in keyof T]: T[K] extends object ? DeepKeyOf<T[K]> : string;
};

function createKeyMap(obj: any, prefix = ''): any {
  const result: any = {};
  for (const key in obj) {
    if (typeof obj[key] === 'object' && obj[key] !== null) {
      result[key] = createKeyMap(obj[key], prefix + key + '.');
    } else {
      result[key] = prefix + key;
    }
  }
  return result;
}

export const STRINGS = createKeyMap(translations.en) as DeepKeyOf<typeof translations.en>;
